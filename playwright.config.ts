import { assertTestEnvironment, testEndpoints } from './scripts/lib/test-target.mjs';
import { defineConfig, devices } from '@playwright/test';
import { auditApp, auditRuntime } from './scripts/lib/audit-test-runtime.mjs';

// Verify destinations before reading runtime credentials or starting any server.
assertTestEnvironment();
Object.assign(process.env, testEndpoints);
const runtime = auditRuntime();
process.env.SUPABASE_SECRET_KEY = runtime.SECRET_KEY;
process.env.NATILLERA_ADMIN_EMAILS ??= 'e2e-admin@example.test';

// Remove elevated credentials from the Vite child. Tests retain their Node-only
// credential in memory; no dotenv file is opened or generated by this entrypoint.
const serverEnv: Record<string, string> = Object.fromEntries(
  Object.keys(process.env).filter(name => /SECRET|SERVICE.*ROLE|PASSWORD|TOKEN/i.test(name)
    || (name.startsWith('VITE_') && !['VITE_SUPABASE_URL', 'VITE_SUPABASE_PUBLISHABLE_KEY'].includes(name)))
    .map(name => [name, ''])
);

export default defineConfig({
  // Keep every spec discoverable; run-e2e prepares synthetic inputs before collection.
  testDir: './e2e',
  outputDir: 'incoming/ci-database/browser-' + (process.env.E2E_PROJECT || 'all'),
  reporter: [['list'], ['json', { outputFile: 'incoming/ci-database/' + (process.env.E2E_PROJECT ? process.env.E2E_PROJECT + '-' : '') + 'results.json' }]],
  timeout: 90_000,
  workers: 1,
  expect: { timeout: 12_000 },
  use: {
    baseURL: auditApp,
    channel: 'chrome',
    serviceWorkers: 'block',
    trace: 'off', actionTimeout: 15_000
  },
  projects: [
    { name: 'chromium', use: { ...devices['Desktop Chrome'] } },
    { name: 'mobile', use: { ...devices['Pixel 7'] } }
  ],
  webServer: {
    command: 'node scripts/start-local-safe.mjs --test',
    env: serverEnv,
    url: auditApp,
    reuseExistingServer: false
  }
});
