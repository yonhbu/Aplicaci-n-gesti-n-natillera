import { defineConfig, devices } from '@playwright/test';
import { createClient } from '@supabase/supabase-js';
import { auditApi, auditApp, auditRuntime } from './scripts/lib/audit-test-runtime.mjs';

// Verify destinations before reading runtime credentials or starting any server.
const requiredEndpoints: Record<string, string> = {
  SUPABASE_URL: auditApi,
  VITE_SUPABASE_URL: auditApi,
  PLAYWRIGHT_BASE_URL: auditApp,
  PLAYWRIGHT_PORT: '5198',
  E2E_MAILPIT_URL: 'http://127.0.0.1:55424',
  SUPABASE_ENV: 'test'
};
for (const [name, expected] of Object.entries(requiredEndpoints)) {
  if (process.env[name] !== undefined && process.env[name] !== expected) {
    throw new Error(`E2E detenido: ${name} no corresponde al destino TEST permitido.`);
  }
  process.env[name] = expected;
}
const runtime = auditRuntime();
process.env.SUPABASE_SECRET_KEY = runtime.SECRET_KEY;
process.env.NATILLERA_ADMIN_EMAILS = 'e2e-admin@example.test';

// Remove elevated credentials from the Vite child. Tests retain their Node-only
// credential in memory; no dotenv file is opened or generated by this entrypoint.
const serverEnv: Record<string, string> = Object.fromEntries(
  Object.keys(process.env).filter(name => /SECRET|SERVICE.*ROLE|PASSWORD|TOKEN/i.test(name)
    || (name.startsWith('VITE_') && !['VITE_SUPABASE_URL', 'VITE_SUPABASE_PUBLISHABLE_KEY'].includes(name)))
    .map(name => [name, ''])
);

async function bootstrapSyntheticE2E() {
  const admin = createClient(auditApi, runtime.SECRET_KEY, {
    auth: { persistSession: false, autoRefreshToken: false }
  });
  const ensure = <T>(result: { data: T; error: unknown }): T => {
    if (result.error) throw new Error('No se pudo preparar el fixture sintético E2E en TEST.');
    return result.data;
  };
  const email = 'e2e-admin@example.test';
  let userId: string | undefined;
  for (let page = 1; !userId; page++) {
    const batch = await admin.auth.admin.listUsers({ page, perPage: 1000 });
    if (batch.error) throw new Error('No se pudo verificar identidad sintética E2E en TEST.');
    const users: Array<{ id: string; email?: string }> = batch.data.users;
    userId = users.find(user => user.email?.toLowerCase() === email)?.id;
    if (batch.data.users.length < 1000) break;
  }
  if (!userId) {
    const created = await admin.auth.admin.createUser({ email, email_confirm: true });
    if (created.error) throw new Error('No se pudo crear identidad sintética E2E.');
    userId = created.data.user.id;
  }
  if (!userId) throw new Error('No se pudo crear identidad sintética E2E.');
  const name = 'Natillera E2E sintética';
  const existing = ensure(await admin.from('workspaces').select('id').eq('name', name).maybeSingle());
  const workspace = existing ?? ensure(await admin.from('workspaces').insert({ name }).select('id').single());
  if (!workspace) throw new Error('No se pudo crear workspace sintético E2E.');
  const cycle = ensure(await admin.from('cycles').select('id').eq('workspace_id', workspace.id).eq('year', 2026).maybeSingle());
  if (!cycle) ensure(await admin.from('cycles').insert({ workspace_id: workspace.id, year: 2026,
    name: 'Natillera E2E 2026', starts_on: '2026-01-01', closes_on: '2026-12-05', status: 'active' }));
  ensure(await admin.from('workspace_users').upsert({ workspace_id: workspace.id, user_id: userId, role: 'admin' }, { onConflict: 'workspace_id,user_id' }));
  console.log('Fixture sintético E2E preparado exclusivamente en TEST55421.');
}

// Invoked by npm run test:e2e before Playwright; configuration loading itself
// performs read-only verification and never bootstraps database records.
if (process.argv.includes('--bootstrap')) {
  await bootstrapSyntheticE2E();
  process.exit(0);
}

export default defineConfig({
  // Preserve legacy discovery. Several historical specs require their own
  // synthetic fixture files; use qa:functional:e2e for this audit's three specs.
  testDir: './e2e',
  timeout: 30_000,
  workers: 1,
  expect: { timeout: 5_000 },
  use: {
    baseURL: auditApp,
    channel: 'chrome',
    trace: 'on-first-retry'
  },
  projects: [
    { name: 'chromium', use: { ...devices['Desktop Chrome'] } },
    { name: 'mobile', use: { ...devices['Pixel 7'] } }
  ],
  webServer: {
    command: 'node scripts/start-local-safe.mjs --test',
    env: serverEnv,
    url: auditApp,
    reuseExistingServer: false
  }
});
